"""
SentinelTrace Backend — AI Agent Schemas

Pydantic models for normalized AI agent inputs, outputs, and structured findings.
"""
from __future__ import annotations

import enum
from datetime import datetime, UTC
from typing import Any
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

class AgentStatus(str, enum.Enum):
    PENDING = "PENDING"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    TIMEOUT = "TIMEOUT"


class RiskVerdict(str, enum.Enum):
    """5-level verdict for the Risk Fusion agent."""
    BENIGN = "BENIGN"
    SUSPICIOUS = "SUSPICIOUS"
    MEDIUM_RISK = "MEDIUM_RISK"
    HIGH_RISK = "HIGH_RISK"
    CRITICAL = "CRITICAL"


class FindingSeverity(str, enum.Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INFO = "INFO"


from app.models.email_analysis import SeverityLevel, ThreatCategory


class AgentFinding(BaseModel):
    """A specific actionable finding generated by an AI agent."""
    model_config = ConfigDict(extra="forbid")

    type: str = Field(..., description="The type/category of the finding (e.g., 'credential_harvesting')")
    severity: FindingSeverity = Field(..., description="Severity of this specific finding")
    description: str = Field(..., description="Detailed explanation of what was found")


class BaseAgentResponse(BaseModel):
    """
    The normalized JSON structure that the LLM must return for all agentic analysis.
    """
    model_config = ConfigDict(extra="forbid")

    risk_score: int = Field(..., ge=0, le=100, description="Risk score from 0 to 100")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence in the analysis from 0.0 to 1.0")
    classification: ThreatCategory = Field(..., description="Primary classification of the threat")
    findings: list[AgentFinding] = Field(default_factory=list, description="Specific identified issues")
    evidence: list[str] = Field(default_factory=list, description="References to deterministic facts supporting the findings")
    recommendations: list[str] = Field(default_factory=list, description="Actionable recommendations")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Agent-specific structured metadata")


class AgentExecutionResult(BaseModel):
    """
    The complete result of an agent execution, wrapping the LLM response with execution context
    and supporting versioning/reruns.
    """
    model_config = ConfigDict(from_attributes=True)

    workspace_id: UUID
    email_analysis_id: UUID
    agent_name: str
    agent_version: str
    prompt_version: str
    model: str
    status: AgentStatus
    
    # Optional fields (present if status is COMPLETED)
    risk_score: int | None = None
    confidence: float | None = None
    classification: ThreatCategory | None = None
    findings: list[AgentFinding] = Field(default_factory=list)
    evidence: list[str] = Field(default_factory=list)
    recommendations: list[str] = Field(default_factory=list)
    metadata: dict[str, Any] = Field(default_factory=dict)
    
    # Execution metadata
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    duration_ms: int | None = None
    error_message: str | None = None


class EvidenceItem(BaseModel):
    source_type: str = Field(..., description="'deterministic' or 'agent'")
    source: str = Field(..., description="The name of the agent or deterministic system")
    description: str = Field(..., description="Description of the evidence")

class RiskFusionResponse(BaseModel):
    """
    The output schema for the Risk Fusion deterministic engine.
    """
    model_config = ConfigDict(extra="forbid")
    
    risk_score: int = Field(..., ge=0, le=100, description="Risk score from 0 to 100")
    verdict: RiskVerdict = Field(..., description="Final 5-level risk verdict")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence in the fusion result")
    summary: str = Field(..., description="High level summary of the verdict")
    key_findings: list[str] = Field(default_factory=list, description="List of strongest findings")
    evidence: list[EvidenceItem] = Field(default_factory=list, description="Provenance-tracked evidence")
    contributing_agents: list[str] = Field(default_factory=list, description="Agents that successfully contributed")
    conflicting_agents: list[str] = Field(default_factory=list, description="Agents that conflicted with the final verdict")
    deterministic_indicators: list[str] = Field(default_factory=list, description="Raw deterministic indicators triggered")
    explanation: str = Field(..., description="Detailed explanation of the final verdict and calculation")

